-- SISTEM PEMBELIAN PERSEDIAAN ATK
-- Jalankan melalui Supabase Dashboard > SQL Editor.
-- Versi ini mendukung pemasok/barang baru yang diketik langsung di formulir.

CREATE TABLE IF NOT EXISTS public.pemasok (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_pemasok VARCHAR(20) UNIQUE NOT NULL,
    nama_pemasok VARCHAR(100) UNIQUE NOT NULL,
    alamat TEXT,
    telepon VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.persediaan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_barang VARCHAR(20) UNIQUE NOT NULL,
    nama_barang VARCHAR(100) UNIQUE NOT NULL,
    satuan VARCHAR(20) NOT NULL DEFAULT 'pcs',
    harga_beli NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (harga_beli >= 0),
    stok INTEGER NOT NULL DEFAULT 0 CHECK (stok >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.pembelian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_pembelian VARCHAR(30) UNIQUE NOT NULL,
    tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    pemasok_id BIGINT NOT NULL REFERENCES public.pemasok(id),
    total NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.detail_pembelian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pembelian_id BIGINT NOT NULL REFERENCES public.pembelian(id) ON DELETE CASCADE,
    persediaan_id BIGINT NOT NULL REFERENCES public.persediaan(id),
    jumlah INTEGER NOT NULL CHECK (jumlah > 0),
    harga_beli NUMERIC(14,2) NOT NULL CHECK (harga_beli >= 0),
    subtotal NUMERIC(14,2) GENERATED ALWAYS AS (jumlah * harga_beli) STORED,
    UNIQUE (pembelian_id, persediaan_id)
);

CREATE OR REPLACE FUNCTION public.catat_pembelian_manual(
    p_no_pembelian TEXT,
    p_tanggal DATE,
    p_nama_pemasok TEXT,
    p_items JSONB
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
    v_pembelian_id BIGINT;
    v_pemasok_id BIGINT;
    v_total NUMERIC(14,2);
    v_item JSONB;
    v_barang_id BIGINT;
    v_nama_barang TEXT;
    v_kode_barang TEXT;
    v_jumlah INTEGER;
    v_harga NUMERIC(14,2);
    v_kode_pemasok TEXT;
BEGIN
    IF p_no_pembelian IS NULL OR LENGTH(TRIM(p_no_pembelian)) = 0 THEN
        RAISE EXCEPTION 'Nomor pembelian wajib diisi';
    END IF;
    IF p_nama_pemasok IS NULL OR LENGTH(TRIM(p_nama_pemasok)) = 0 THEN
        RAISE EXCEPTION 'Nama pemasok wajib diisi';
    END IF;
    IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array'
       OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Detail pembelian tidak boleh kosong';
    END IF;

    -- Buat pemasok otomatis bila nama belum ada.
    SELECT id INTO v_pemasok_id
    FROM public.pemasok
    WHERE LOWER(nama_pemasok) = LOWER(TRIM(p_nama_pemasok))
    LIMIT 1;

    IF v_pemasok_id IS NULL THEN
        v_kode_pemasok := 'SUP-' || UPPER(SUBSTRING(MD5(LOWER(TRIM(p_nama_pemasok))) FROM 1 FOR 10));
        INSERT INTO public.pemasok(kode_pemasok, nama_pemasok)
        VALUES (v_kode_pemasok, TRIM(p_nama_pemasok))
        ON CONFLICT (nama_pemasok) DO UPDATE SET nama_pemasok = EXCLUDED.nama_pemasok
        RETURNING id INTO v_pemasok_id;
    END IF;

    -- Validasi semua item terlebih dahulu.
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
    LOOP
        IF jsonb_typeof(v_item) <> 'object'
           OR NOT (v_item ? 'nama_barang')
           OR NOT (v_item ? 'jumlah')
           OR NOT (v_item ? 'harga_beli') THEN
            RAISE EXCEPTION 'Format detail pembelian tidak valid';
        END IF;

        v_nama_barang := TRIM(v_item->>'nama_barang');
        IF v_nama_barang IS NULL OR v_nama_barang = '' THEN
            RAISE EXCEPTION 'Nama barang wajib diisi';
        END IF;

        IF v_item->>'jumlah' !~ '^[1-9][0-9]*$'
           OR v_item->>'harga_beli' !~ '^[0-9]+(\.[0-9]{1,2})?$' THEN
            RAISE EXCEPTION 'Jumlah atau harga tidak valid';
        END IF;

        v_jumlah := (v_item->>'jumlah')::INTEGER;
        v_harga := (v_item->>'harga_beli')::NUMERIC;
        IF v_jumlah <= 0 OR v_harga < 0 OR v_harga > 999999999999.99 THEN
            RAISE EXCEPTION 'Jumlah atau harga di luar batas';
        END IF;
    END LOOP;

    IF (
        SELECT COUNT(*) FROM jsonb_array_elements(p_items)
    ) <> (
        SELECT COUNT(DISTINCT LOWER(TRIM(value->>'nama_barang')))
        FROM jsonb_array_elements(p_items)
    ) THEN
        RAISE EXCEPTION 'Nama barang yang sama tidak boleh diinput dua kali';
    END IF;

    INSERT INTO public.pembelian(no_pembelian, tanggal, pemasok_id, total)
    VALUES (TRIM(p_no_pembelian), COALESCE(p_tanggal, CURRENT_DATE), v_pemasok_id, 0)
    RETURNING id INTO v_pembelian_id;

    FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
    LOOP
        v_nama_barang := TRIM(v_item->>'nama_barang');
        v_jumlah := (v_item->>'jumlah')::INTEGER;
        v_harga := (v_item->>'harga_beli')::NUMERIC;

        SELECT id INTO v_barang_id
        FROM public.persediaan
        WHERE LOWER(nama_barang) = LOWER(v_nama_barang)
        LIMIT 1;

        IF v_barang_id IS NULL THEN
            v_kode_barang := 'ATK-' || UPPER(SUBSTRING(MD5(LOWER(v_nama_barang)) FROM 1 FOR 10));
            INSERT INTO public.persediaan(kode_barang, nama_barang, satuan, harga_beli, stok)
            VALUES (v_kode_barang, v_nama_barang, COALESCE(NULLIF(TRIM(v_item->>'satuan'), ''), 'pcs'), v_harga, 0)
            ON CONFLICT (nama_barang) DO UPDATE SET nama_barang = EXCLUDED.nama_barang
            RETURNING id INTO v_barang_id;
        END IF;

        UPDATE public.persediaan
        SET stok = stok + v_jumlah, harga_beli = v_harga
        WHERE id = v_barang_id;

        INSERT INTO public.detail_pembelian(pembelian_id, persediaan_id, jumlah, harga_beli)
        VALUES (v_pembelian_id, v_barang_id, v_jumlah, v_harga);
    END LOOP;

    SELECT COALESCE(SUM(subtotal), 0) INTO v_total
    FROM public.detail_pembelian WHERE pembelian_id = v_pembelian_id;

    UPDATE public.pembelian SET total = v_total WHERE id = v_pembelian_id;
    RETURN v_pembelian_id;
END;
$$;

